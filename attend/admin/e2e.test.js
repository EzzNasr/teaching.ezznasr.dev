// node tests/e2e.test.js : real Attendance/AttFlags/AttTelegram .gs + real client token/api code, emulated Apps Script.
const assert = require("assert"), path = require("path");
const { build } = require("./gas_emulator.js");
const site = path.join(__dirname, "..", "site");
global.ATT_CONFIG = require(path.join(site, "contract/att_config.js"));
const TOKEN = require(path.join(site, "attend/admin/token.js"));
const gas = build();
global.ATT_FETCH = async (_u, init) => ({ json: async () => JSON.parse(JSON.stringify(gas.ctx.att_dispatch_(JSON.parse(init.body)))) });
const api = require(path.join(site, "contract/att_api.js"));
let pass = 0; const ok = (c, m) => { assert.ok(c, m); pass++; console.log("  ok  " + m); };
const A = { token: "adm-secret" };
const geoHere = (d = 0) => ({ lat: 31.2001 + d, lng: 29.9187, acc: 20 + Math.random() });
async function ticket(sid, key) {
  const w = TOKEN.windowOf(Date.now());
  return api.call("att_ticket", { session_id: sid, token: await TOKEN.token(key, sid, w) });
}
(async () => {
  console.log("setup");
  const st = gas.run("att_setup('SS1')");
  ok(st.ok && st.admin_token_found && gas.sheets.AttCheckins, "att_setup creates tabs + finds ADMIN_TOKEN");
  console.log("admin");
  ok((await api.call("att_rooms", {})).code === "UNAUTHORIZED", "admin action without token rejected");
  const cal = await api.call("att_calibrate_room", { ...A, name: "Hall 1", samples: Array.from({ length: 10 }, () => geoHere()) });
  ok(cal.ok && cal.room.room_id, "calibrate room");
  const start = await api.call("att_start_session", { ...A, course: "CS101", room_id: cal.room.room_id });
  ok(start.ok && start.session_key.length === 64, "start session returns 64-hex session_key");
  const sid = start.session_id, key = start.session_key;
  assert.ok(gas.sent.some(m => /session started/i.test(m.text))); ok(true, "Telegram: session start message");
  console.log("student A");
  const bad = await api.call("att_ticket", { session_id: sid, token: "0000000000000000" });
  ok(bad.code === "TOKEN_EXPIRED", "wrong QR token rejected");
  const t1 = await ticket(sid, key); ok(t1.ok && t1.ticket, "browser-computed token accepted by server (WebCrypto == Apps Script HMAC)");
  ok((await api.call("att_signup", { ticket: t1.ticket, student_id: "abc", name: "Test Name", secret: "A".repeat(64), fp: "f1", geo: geoHere() })).code === "BAD_ID", "bad ID format rejected");
  const su = await api.call("att_signup", { ticket: t1.ticket, student_id: "20240001", name: "Ali", secret: "A".repeat(64), fp: "f1", geo: geoHere() });
  ok(su.ok && su.status === "registered", "sign-up");
  const at = await api.call("att_attend", { ticket: t1.ticket, student_id: "20240001", secret: "A".repeat(64), fp: "f1", geo: geoHere() });
  ok(at.ok && at.status === "recorded" && !("flags" in at), "attend recorded, no flags leaked");
  const at2 = await api.call("att_attend", { ticket: t1.ticket, student_id: "20240001", secret: "A".repeat(64), fp: "f1", geo: geoHere() });
  ok(at2.ok, "second scan is idempotent");
  console.log("first-time student flow (the bug seen in the live test)");
  ok(at.name === "Ali", "attend returns the registered name for the welcome line");
  const logRows = gas.sheets.AttFlagLog.getLastRow(), sentN = gas.sent.length;
  const fresh = await api.call("att_attend", { ticket: t1.ticket, student_id: "20249999", secret: "9".repeat(64), fp: "f", geo: geoHere() });
  ok(fresh.code === "UNKNOWN_STUDENT", "never-registered ID -> UNKNOWN_STUDENT (page then registers)");
  ok(gas.sheets.AttFlagLog.getLastRow() === logRows, "...and nothing is written to the flag log");
  gas.run("att_flushDigest()");
  ok(gas.sent.slice(sentN).every(m => !/20249999/.test(m.text)), "...and nothing reaches Telegram");
  ok((await api.call("att_signup", { ticket: t1.ticket, student_id: "20249998", secret: "8".repeat(64), fp: "f", geo: geoHere() })).code === "NAME_REQUIRED", "sign-up without a name rejected");
  ok((await api.call("att_signup", { ticket: t1.ticket, student_id: "20249998", name: " ", secret: "8".repeat(64), fp: "f", geo: geoHere() })).code === "NAME_REQUIRED", "blank name rejected");
  const dup = await api.call("att_start_session", { ...A, course: "CS101", room_id: cal.room.room_id });
  ok(dup.ok && dup.session_id === sid && dup.session_key === key, "second Start within 20 s returns the SAME session (no duplicate)");
  ok(gas.sent.filter(m => /session started/i.test(m.text)).length === 1, "only one 'session started' Telegram message");
  console.log("conflicts");
  ok((await api.call("att_signup", { ticket: t1.ticket, student_id: "20240001", name: "Test Name", secret: "B".repeat(64), fp: "f2", geo: geoHere() })).code === "ID_TAKEN", "ID already registered -> ID_TAKEN");
  ok((await api.call("att_signup", { ticket: t1.ticket, student_id: "20240002", name: "Test Name", secret: "A".repeat(64), fp: "f1", geo: geoHere() })).code === "DEVICE_BOUND_OTHER_ID", "same phone, second ID -> DEVICE_BOUND_OTHER_ID");
  ok((await api.call("att_attend", { ticket: t1.ticket, student_id: "20240009", secret: "A".repeat(64), fp: "f1", geo: geoHere() })).code === "DEVICE_ID_CONFLICT", "bound device typing another ID -> DEVICE_ID_CONFLICT");
  ok((await api.call("att_attend", { ticket: t1.ticket, student_id: "20240001", secret: "Z".repeat(64), fp: "f9", geo: geoHere() })).code === "DEVICE_UNKNOWN", "unknown device for registered ID -> DEVICE_UNKNOWN");
  console.log("device change + Telegram approval");
  const ch = await api.call("att_change_device", { ticket: t1.ticket, student_id: "20240001", new_secret: "C".repeat(64), fp: "f1" });
  ok(ch.ok && ch.status === "pending" && ch.req_id, "change-device request pending");
  const dr = gas.sent.filter(m => m.markup).pop();
  ok(dr && /ad:/.test(JSON.stringify(dr.markup)) && /dd:/.test(JSON.stringify(dr.markup)), "Telegram: Approve/Deny buttons use ad:/dd: prefixes");
  ok(/same phone/i.test(dr.text), "Telegram: fingerprint-match hint present");
  ok(gas.tgCalls.every(c => c.token === "NEWBOT:token"), "every Telegram call used the NEW bot token");
  ok(gas.sent.every(m => m.chat === "111"), "messages went only to ATT_TG_ADMIN_IDS");
  const verdict = gas.run(`att_decideFromTelegram_(${JSON.stringify(ch.req_id)}, true)`);
  ok(/Approved/.test(verdict), "Telegram tap approves: " + verdict);
  ok(/not approved|⚠/.test(gas.run(`att_decideFromTelegram_(${JSON.stringify(ch.req_id)}, true)`)), "double decision (page + Telegram) rejected");
  const t2 = await ticket(sid, key);
  ok((await api.call("att_attend", { ticket: t2.ticket, student_id: "20240001", secret: "C".repeat(64), fp: "f1", geo: geoHere() })).ok, "new device works after approval");
  ok((await api.call("att_attend", { ticket: t2.ticket, student_id: "20240001", secret: "A".repeat(64), fp: "f1", geo: geoHere() })).code === "ID_BOUND_OTHER_DEVICE", "old device now revoked");
  console.log("flags");
  const far = { lat: 31.25, lng: 29.9187, acc: 20 };
  for (const [i, g] of [[3, far], [4, { denied: true }]]) {
    const s = "2024000" + i, sec = String(i).repeat(64);
    const t = await ticket(sid, key);
    await api.call("att_signup", { ticket: t.ticket, student_id: s, name: "Test Name", secret: sec, fp: "fp" + i, geo: g });
    const r = await api.call("att_attend", { ticket: t.ticket, student_id: s, secret: sec, fp: "fp" + i, geo: g });
    ok(r.ok && r.status === "recorded", `${s}: far/denied still shown as recorded`);
  }
  const fl = await api.call("att_flagged", { ...A, session_id: sid });
  const codes = fl.rows.map(r => r.flags).join(",");
  ok(fl.ok && /GEO_FAR/.test(codes) && /GEO_DENIED/.test(codes), "flagged view lists GEO_FAR and GEO_DENIED: " + codes);
  const live = await api.call("att_live", { ...A, session_id: sid });
  ok(live.ok && live.present >= 3 && live.flagged === 2 && typeof live.pending === "number", `live counters present=${live.present} flagged=${live.flagged}`);
  console.log("roster");
  const ro = await api.call("att_roster", { ...A });
  ok(ro.ok && ro.sessions.some(x => x.session_id === sid) && ro.courses.includes("CS101"), "att_roster returns sessions + course list");
  ok(ro.students.some(x => x.student_id === "20240001" && x.name === "Ali"), "roster lists students with ID and name");
  ok(ro.marks.some(m => m[0] === sid && m[1] === "20240001" && /^\d{4}-\d\d-\d\dT/.test(m[2])), "roster marks carry the server check-in time");
  ok(!JSON.stringify(ro).includes("secret"), "roster leaks no secrets");
  ok((await api.call("att_roster", {})).code === "UNAUTHORIZED", "roster needs the admin token");
  ok((await api.call("att_roster", { ...A, course: "NOPE" })).sessions.length === 0, "course filter works");
  console.log("close + export");
  const cl = await api.call("att_close_session", { ...A, session_id: sid });
  ok(cl.ok && cl.summary.present >= 3 && cl.summary.flagged === 2, "close summary");
  const late = await ticket(sid, key); ok(late.code === "SESSION_CLOSED", "closed session rejects new tickets");
  const ex = await api.call("att_export", { ...A, session_id: sid });
  ok(ex.ok && /^student_id,name,server_utc/.test(ex.csv), "CSV export");
  console.log("\n" + pass + " checks passed");
})().catch(e => { console.error("\nFAIL:", e.message); process.exit(1); });
