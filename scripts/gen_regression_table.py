#!/usr/bin/env python3
"""Regenerate the table in docs/REGRESSION.md from tools/quiz-maker-v2/tests/registry.json.

    python scripts/gen_regression_table.py          rewrite the table between the two markers
    python scripts/gen_regression_table.py --check  exit 1 if the table is out of date (run by the gate, R-DOC-1)

The JSON is the source; the table is for people. A registry entry added without regenerating fails the gate, so
the doc can no longer fall behind the tests (it had: ~50 rows for 130 entries, as of 2026-11-03).
"""
import json
import os
import sys

SITE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(SITE, "tools", "quiz-maker-v2", "tests", "registry.json")
DOC = os.path.join(SITE, "docs", "REGRESSION.md")
START, END = "<!-- registry-table:start (generated by scripts/gen_regression_table.py; do not edit by hand) -->", "<!-- registry-table:end -->"


def cell(s):
    return str(s).replace("|", "\\|").replace("\n", " ").strip()


def test_of(e, by_id):
    if e.get("same_run_as"):
        return "(runs with %s)" % e["same_run_as"]
    cmd = e.get("cmd") or []
    files = [c for c in cmd[1:] if not c.startswith("-")]
    if not files:
        return "(to write) `%s`" % e["expected_file"] if e.get("expected_file") else "(no command)"
    return "`%s`" % files[0].replace("../../", "")


def table():
    reg = json.load(open(REG, encoding="utf-8"))
    by_id = {e["id"]: e for e in reg["entries"]}
    rows = ["| ID | Case | Status | Needs | Test |", "|---|---|---|---|---|"]
    for e in reg["entries"]:
        st = e["status"] + (" (%s)" % e["owner"] if e["status"] == "pending" else "")
        if e["status"] == "retired" and e.get("note"):
            st += ": " + e["note"]
        needs = e.get("needs") or ""
        if isinstance(needs, list):
            needs = ", ".join(needs)
        rows.append("| %s | %s | %s | %s | %s |" % (e["id"], cell(e.get("title", "")), cell(st), cell(needs), test_of(e, by_id)))
    counts = {}
    for e in reg["entries"]:
        counts[e["status"]] = counts.get(e["status"], 0) + 1
    summary = "%d entries: " % len(reg["entries"]) + ", ".join("%d %s" % (n, s) for s, n in sorted(counts.items()))
    return START + "\n\n" + summary + ". Browser tests (Needs = playwright) run with `--e2e`; CI runs everything with `--require-all`.\n\n" + "\n".join(rows) + "\n\n" + END


def main():
    doc = open(DOC, encoding="utf-8").read().replace("\r\n", "\n")
    new = table()
    if START in doc and END in doc:
        a, b = doc.index(START), doc.index(END) + len(END)
        out = doc[:a] + new + doc[b:]
    else:  # first run: replace the old hand-kept table under "## The registry"
        h = doc.index("## The registry")
        t0 = doc.index("\n| ID |", h)
        t1 = doc.index("\n## ", t0 + 1)
        out = doc[:t0] + "\n\n" + new + "\n" + doc[t1:]
    if "--check" in sys.argv:
        if out != doc:
            print("FAIL docs/REGRESSION.md table is out of date: run  python scripts/gen_regression_table.py")
            return 1
        print("PASS docs/REGRESSION.md table matches tests/registry.json")
        return 0
    open(DOC, "w", encoding="utf-8", newline="\n").write(out)
    print("wrote " + os.path.relpath(DOC, SITE))
    return 0


if __name__ == "__main__":
    sys.exit(main())
