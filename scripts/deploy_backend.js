#!/usr/bin/env node
// Deploy the Apps Script backend from the repo with clasp (refactor step 2.5). Replaces copy and paste.
//
//   node scripts/deploy_backend.js           dry run: every check, then shows what would change. Changes nothing.
//   node scripts/deploy_backend.js --yes     deploy
//
// Options:
//   --allow-branch   deploy a commit that is not origin/main (a hotfix or a rollback to an older commit)
//   --skip-gate      do not run the fast test gate first (CI already ran the full one on main)
//   --allow-drift    deploy even if the editor holds saved code that was never deployed (it is overwritten)
//
// What a deploy does, in order (any failure stops it):
//   1. Preflight: clean working tree; HEAD is on GitHub; HEAD == origin/main unless --allow-branch.
//   2. Fast test gate (scripts/test_all.sh --strict).
//   3. Live check: clone the editor's saved code and the deployed version into a temp folder. They must be equal:
//      time-driven triggers run the SAVED code, so a difference means code is running that was never deployed.
//      The manifest (appsscript.json) must equal the repo's. Prints which files this deploy changes.
//   4. Stage: the repo files under the editor's names, in the editor's order, plus a generated Version.gs
//      (APP_VERSION = commit + time; doGet returns it).
//   5. clasp push, then clone again and prove the saved code is exactly what was staged.
//   6. clasp create-version, then clasp update-deployment on the SAME deployment id (the /exec URL never changes).
//   7. Live smoke test (scripts/smoke_live.js --expect-commit <sha>).
//   8. Smoke failed: automatic rollback (push the previous version's files back, point the deployment at it again).
//   9. Record a row in docs/runbooks/backend-deploys.md (commit it afterwards).
//
// Never run this during a class or a quiz window (plan rule 6). The old paste procedure still works as a fallback.
'use strict';
const fs = require('fs'), os = require('os'), path = require('path'), cp = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const GS_DIR = path.join(ROOT, 'tools', 'quiz-maker-v2', 'apps_script');
const LOG = path.join(ROOT, 'docs', 'runbooks', 'backend-deploys.md');

// ---------- pure helpers (unit-tested in tests/test_deploy_backend.js) ----------

const norm = s => String(s).replace(/\r\n?/g, '\n').replace(/\n*$/, '\n');

function loadConfig(dir = GS_DIR) {
  const c = JSON.parse(fs.readFileSync(path.join(dir, 'deploy.json'), 'utf8'));
  if (!c.scriptId || !c.deploymentId || !Array.isArray(c.files) || !c.files.length) throw new Error('deploy.json: scriptId, deploymentId and files are required');
  const names = new Set();
  c.files.forEach(f => {
    if (!f.live || (!f.repo && f.generated !== 'version')) throw new Error('deploy.json: bad file entry ' + JSON.stringify(f));
    if (names.has(f.live.toLowerCase())) throw new Error('deploy.json: duplicate live name ' + f.live);
    names.add(f.live.toLowerCase());
  });
  if (c.files.filter(f => f.generated === 'version').length !== 1) throw new Error('deploy.json: exactly one generated version file is required');
  return c;
}

/** Every top-level .gs file in the repo folder must be listed, and every listed file must exist. */
function checkRepoFiles(cfg, dir = GS_DIR) {
  const listed = cfg.files.filter(f => f.repo).map(f => f.repo).sort();
  const present = fs.readdirSync(dir).filter(f => /\.gs$/.test(f)).sort();
  const missing = listed.filter(f => present.indexOf(f) === -1), unlisted = present.filter(f => listed.indexOf(f) === -1);
  return { ok: !missing.length && !unlisted.length, missing, unlisted };
}

function versionSource(info) {
  return '// GENERATED by scripts/deploy_backend.js at deploy time. Not in the repo; do not edit in the editor.\n' +
    'var APP_VERSION = ' + JSON.stringify({ commit: info.commit, short: info.commit.slice(0, 7), deployed_at: info.deployedAt, branch: info.branch || '' }) + ';\n';
}

/** The .clasp.json and the files for a push folder. Returns { files: {name: text}, clasp: {...} }. */
function stage(cfg, info, readRepo) {
  const files = {}, order = [];
  cfg.files.forEach(f => {
    const name = f.live + '.gs';
    files[name] = f.generated ? versionSource(info) : readRepo(f.repo);
    order.push(name);
  });
  files['appsscript.json'] = readRepo('appsscript.json');
  return { files, clasp: { scriptId: cfg.scriptId, rootDir: '.', scriptExtensions: ['.gs'], filePushOrder: order } };
}

/** A clasp clone/pull folder as { liveName: text }. clasp writes server files as .js (a file named "Revenue.gs" becomes Revenue.gs.js). */
function readLive(dir) {
  const out = {};
  fs.readdirSync(dir).forEach(f => {
    if (f === 'appsscript.json') out[f] = fs.readFileSync(path.join(dir, f), 'utf8');
    else if (/\.(js|gs)$/.test(f)) out[f.replace(/\.(js|gs)$/, '')] = fs.readFileSync(path.join(dir, f), 'utf8');
  });
  return out;
}

/** Compare two { name: text } maps (names compared case-sensitively, text with line endings normalised). */
function compare(a, b) {
  const names = Array.from(new Set(Object.keys(a).concat(Object.keys(b)))).sort();
  const changed = [], onlyA = [], onlyB = [], same = [];
  names.forEach(n => {
    if (!(n in b)) onlyA.push(n);
    else if (!(n in a)) onlyB.push(n);
    else if (n === 'appsscript.json' ? !sameJson(a[n], b[n]) : norm(a[n]) !== norm(b[n])) changed.push(n);
    else same.push(n);
  });
  return { equal: !changed.length && !onlyA.length && !onlyB.length, changed, onlyA, onlyB, same };
}
function sameJson(x, y) { try { return JSON.stringify(sortKeys(JSON.parse(x))) === JSON.stringify(sortKeys(JSON.parse(y))); } catch (e) { return false; } }
function sortKeys(v) { return Array.isArray(v) ? v.map(sortKeys) : v && typeof v === 'object' ? Object.keys(v).sort().reduce((o, k) => (o[k] = sortKeys(v[k]), o), {}) : v; }

/** "- <id> @69 desc" lines from clasp list-deployments. Returns the version number of deploymentId, or null (@HEAD / missing). */
function deployedVersion(listOutput, deploymentId) {
  const line = String(listOutput).split(/\r?\n/).find(l => l.indexOf(deploymentId) !== -1);
  const m = line && /@(\d+)/.exec(line);
  return m ? Number(m[1]) : null;
}
function createdVersion(output) {
  const m = /version\s+(\d+)/i.exec(String(output));
  if (!m) throw new Error('could not read the new version number from: ' + String(output).trim());
  return Number(m[1]);
}
function logRow(r) {
  return `| ${r.date} | ${r.version} | \`${r.commit.slice(0, 7)}\` | ${r.previous} | ${r.changed.join(', ') || 'none'} | ${r.result} |\n`;
}
const LOG_HEAD = '# Backend deploys\n\n*Written by `scripts/deploy_backend.js`, one row per scripted deploy (newest last). Commit this file after a deploy.\n' +
  'Roll back: `git checkout <commit of the previous row>` then `node scripts/deploy_backend.js --yes --allow-branch`.\n' +
  'Older, hand-pasted deploys are recorded in `docs/attendance/decisions.md`.*\n\n' +
  '| Date (Cairo) | Version | Commit | Previous version | Files changed | Result |\n|---|---|---|---|---|---|\n';

// ---------- the run (side effects go through `sh`, so tests can fake every command) ----------

function realSh() {
  const claspDir = path.join(ROOT, 'node_modules', '@google', 'clasp');   // its package.json is not in "exports", so read it directly
  if (!fs.existsSync(path.join(claspDir, 'package.json'))) throw new Error('clasp is not installed: run npm ci (then npx clasp login once)');
  const bin = JSON.parse(fs.readFileSync(path.join(claspDir, 'package.json'), 'utf8')).bin;
  const claspBin = path.join(claspDir, typeof bin === 'string' ? bin : bin.clasp);
  return function sh(cmd, args, opts = {}) {
    const exe = cmd === 'clasp' || cmd === 'node' ? process.execPath : cmd;
    const argv = cmd === 'clasp' ? [claspBin].concat(args) : args;
    const r = cp.spawnSync(exe, argv, { cwd: opts.cwd || ROOT, encoding: 'utf8', stdio: opts.inherit ? 'inherit' : 'pipe', shell: false });
    if (r.error) throw r.error;
    if (r.status !== 0 && !opts.allowFail) throw new Error(`${cmd} ${args.join(' ')} failed (${r.status}):\n${(r.stderr || '') + (r.stdout || '')}`.trim());
    return { code: r.status, out: (r.stdout || '') + (r.stderr || '') };
  };
}

function cairoNow(d = new Date()) {
  return new Intl.DateTimeFormat('sv-SE', { timeZone: 'Africa/Cairo', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit' }).format(d);
}

async function run(argv, deps = {}) {
  const sh = deps.sh || realSh(), say = deps.say || (s => console.log(s));
  const fsx = deps.fs || fs, tmpRoot = deps.tmp || fs.mkdtempSync(path.join(os.tmpdir(), 'gas-deploy-'));
  const opt = { yes: argv.includes('--yes'), allowBranch: argv.includes('--allow-branch'), skipGate: argv.includes('--skip-gate'), allowDrift: argv.includes('--allow-drift') };
  const cfg = deps.cfg || loadConfig();
  const readRepo = deps.readRepo || (f => fs.readFileSync(path.join(GS_DIR, f), 'utf8'));
  const step = s => say('\n== ' + s + ' ==');

  step('1. preflight');
  if (!deps.cfg) { const rf = checkRepoFiles(cfg); if (!rf.ok) throw new Error('deploy.json and the .gs files disagree. missing: ' + rf.missing.join(', ') + '; not listed: ' + rf.unlisted.join(', ')); }
  if (sh('git', ['status', '--porcelain', '--untracked-files=no']).out.trim()) throw new Error('the working tree has uncommitted changes: commit or stash them first');
  const commit = sh('git', ['rev-parse', 'HEAD']).out.trim();
  const branch = sh('git', ['rev-parse', '--abbrev-ref', 'HEAD']).out.trim();
  sh('git', ['fetch', '--quiet', 'origin']);
  if (!sh('git', ['branch', '-r', '--contains', commit]).out.trim()) throw new Error('commit ' + commit.slice(0, 7) + ' is not on GitHub: push it first, so the deployed commit can be found later');
  const main = sh('git', ['rev-parse', 'origin/main']).out.trim();
  if (commit !== main && !opt.allowBranch) throw new Error(`HEAD (${commit.slice(0, 7)}) is not origin/main (${main.slice(0, 7)}). Deploy main, or pass --allow-branch on purpose`);
  say(`commit ${commit.slice(0, 7)} on ${branch}${commit === main ? ' (= origin/main)' : ' (NOT main: --allow-branch)'}`);

  step('2. fast test gate');
  if (opt.skipGate) say('skipped (--skip-gate)');
  else {
    const g = sh('bash', ['scripts/test_all.sh', '--strict'], { allowFail: true });
    if (g.code !== 0 || !/ALL GREEN/.test(g.out)) { say(g.out.split('\n').slice(-15).join('\n')); throw new Error('the test gate is not green'); }
    say('ALL GREEN');
  }

  step('3. live check');
  const deps0 = sh('clasp', ['list-deployments', cfg.scriptId]).out;
  const prev = deployedVersion(deps0, cfg.deploymentId);
  if (!prev) throw new Error('could not find a numbered version for deployment ' + cfg.deploymentId.slice(0, 12) + '...:\n' + deps0);
  const headDir = path.join(tmpRoot, 'saved'), prevDir = path.join(tmpRoot, 'deployed');
  fsx.mkdirSync(headDir, { recursive: true }); fsx.mkdirSync(prevDir, { recursive: true });
  sh('clasp', ['clone', cfg.scriptId, '--rootDir', '.'], { cwd: headDir });
  fsx.copyFileSync(path.join(headDir, '.clasp.json'), path.join(prevDir, '.clasp.json'));
  sh('clasp', ['pull', '--versionNumber', String(prev)], { cwd: prevDir });
  const saved = readLive(headDir), deployed = readLive(prevDir);
  const drift = compare(saved, deployed);
  if (!drift.equal) {
    say(`The editor's saved code differs from deployed Version ${prev}: ${drift.changed.concat(drift.onlyA, drift.onlyB).join(', ')}`);
    say('Time-driven triggers already run that saved code. Find out who changed what before deploying over it.');
    if (!opt.allowDrift) throw new Error('saved code is not the deployed code (pass --allow-drift to overwrite it on purpose)');
  } else say(`saved code = deployed Version ${prev}`);
  const staged = stage(cfg, { commit, deployedAt: cairoNow(deps.now), branch }, readRepo);
  if (!sameJson(staged.files['appsscript.json'], deployed['appsscript.json'] || '{}')) throw new Error('the live manifest (appsscript.json) differs from the repo: copy it into the repo on purpose first');
  const want = {}; Object.keys(staged.files).forEach(n => { want[n.replace(/\.gs$/, '')] = staged.files[n]; });
  const verFile = cfg.files.find(f => f.generated).live;
  const plan = compare(want, deployed);
  const changes = plan.changed.concat(plan.onlyA.map(n => n + ' (new)'), plan.onlyB.map(n => n + ' (REMOVED)')).filter(n => n.indexOf(verFile) !== 0);
  say(`Version ${prev} -> this commit: ${changes.length ? changes.join(', ') : 'no file changes besides ' + verFile}`);

  if (!opt.yes) { step('dry run'); say('Nothing was changed. Run again with --yes to deploy.'); return { dryRun: true, prev, changes }; }

  step('4-5. stage and push');
  const pushDir = path.join(tmpRoot, 'push'); fsx.mkdirSync(pushDir, { recursive: true });
  fsx.writeFileSync(path.join(pushDir, '.clasp.json'), JSON.stringify(staged.clasp, null, 2));
  Object.keys(staged.files).forEach(n => fsx.writeFileSync(path.join(pushDir, n), staged.files[n]));
  sh('clasp', ['push', '--force'], { cwd: pushDir });
  const checkDir = path.join(tmpRoot, 'check'); fsx.mkdirSync(checkDir, { recursive: true });
  sh('clasp', ['clone', cfg.scriptId, '--rootDir', '.'], { cwd: checkDir });
  const pushed = compare(want, readLive(checkDir));
  if (!pushed.equal) { await rollback('the saved code after push differs from what was staged: ' + pushed.changed.concat(pushed.onlyA, pushed.onlyB).join(', ')); }
  say('pushed and verified');

  step('6. version and deployment');
  const version = createdVersion(sh('clasp', ['create-version', `${commit.slice(0, 7)} ${branch}`]).out);
  sh('clasp', ['update-deployment', cfg.deploymentId, '--versionNumber', String(version), '--description', commit.slice(0, 7)]);
  say(`Version ${version} is live on the same deployment (rollback target: Version ${prev})`);

  step('7. live smoke test');
  const url = `https://script.google.com/macros/s/${cfg.deploymentId}/exec`;
  const smoke = sh('node', ['scripts/smoke_live.js', url, '--expect-commit', commit], { allowFail: true });
  say(smoke.out.trim());
  if (smoke.code !== 0) await rollback('the live smoke test failed', version);

  step('9. record');
  record({ version, commit, previous: prev, changed: changes, result: 'smoke green' });
  say(`Recorded in ${path.relative(ROOT, LOG)}. Commit it. Done: Version ${version} = ${commit.slice(0, 7)}.`);
  return { dryRun: false, prev, version, changes };

  async function rollback(why, newVersion) {
    step('8. ROLLBACK: ' + why);
    const back = path.join(tmpRoot, 'rollback'); fsx.mkdirSync(back, { recursive: true });
    const order = cfg.files.map(f => f.live + '.gs').filter(n => (n.replace(/\.gs$/, '') in deployed));
    fsx.writeFileSync(path.join(back, '.clasp.json'), JSON.stringify({ scriptId: cfg.scriptId, rootDir: '.', scriptExtensions: ['.gs'], filePushOrder: order }, null, 2));
    Object.keys(deployed).forEach(n => fsx.writeFileSync(path.join(back, n === 'appsscript.json' ? n : n + '.gs'), deployed[n]));
    sh('clasp', ['push', '--force'], { cwd: back });
    sh('clasp', ['update-deployment', cfg.deploymentId, '--versionNumber', String(prev), '--description', 'rollback']);
    record({ version: newVersion || '-', commit, previous: prev, changed: changes, result: 'ROLLED BACK to Version ' + prev + ': ' + why });
    throw new Error(`${why}. Rolled back: saved code and the deployment are Version ${prev} again. Check with: node scripts/smoke_live.js`);
  }
  function record(r) {
    const w = deps.writeLog || (row => { if (!fs.existsSync(LOG)) fs.writeFileSync(LOG, LOG_HEAD); fs.appendFileSync(LOG, row); });
    w(logRow(Object.assign({ date: cairoNow(deps.now) }, r)));
  }
}

module.exports = { norm, loadConfig, checkRepoFiles, versionSource, stage, readLive, compare, deployedVersion, createdVersion, logRow, run, LOG_HEAD };

if (require.main === module) {
  run(process.argv.slice(2)).catch(e => { console.error('\nSTOPPED: ' + e.message); process.exit(1); });
}
