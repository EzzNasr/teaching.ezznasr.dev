// node tests/attendance/feed.test.js : the live activity feed + the two-mates cheating scenario, on the emulated backend.
const assert = require("assert"), path = require("path");
const { build } = require("./gas_emulator.js");
const site = path.join(__dirname, "..", "..");
global.ATT_CONFIG = require(path.join(site, "contract/att_config.js"));
const TOKEN = require(path.join(site, "attend/admin/token.js"));
const gas = build();
global.ATT_FETCH = async (_u, init) => ({ json: async () => JSON.parse(JSON.stringify(gas.ctx.att_dispatch_(JSON.parse(init.body)))) });
const api = require(path.join(site, "contract/att_api.js"));
let pass = 0; const ok = (c, m) => { assert.ok(c, m); pass++; console.log("  ok  " + m); };
const A = { token: "adm-secret" }, geo = () => ({ lat: 31.2001, lng: 29.9187, acc: 20 });
(async () => {
  gas.run("att_setup('SS1')");
  const cal = await api.call("att_calibrate_room", { ...A, name: "Hall 1", samples: Array.from({ length: 10 }, geo) });
  const st = await api.call("att_start_session", { ...A, course: "CS101", room_id: cal.room.room_id });
  const sid = st.session_id, key = st.session_key;
  const tk = async () => (await api.call("att_ticket", { session_id: sid, token: await TOKEN.token(key, sid, TOKEN.windowOf(Date.now())) })).ticket;
  const reg = async (id, name, sec) => api.call("att_signup", { ticket: await tk(), student_id: id, name, secret: sec.repeat(64), fp: "f" + sec, geo: geo() });
  const att = async (id, sec) => api.call("att_attend", { ticket: await tk(), student_id: id, secret: sec.repeat(64), fp: "f" + sec, geo: geo() });
  console.log("two mates register");
  ok((await reg("20240011", "Mona Adel", "A")).ok, "mate 1 registers");
  ok((await reg("20240022", "Karim Said", "B")).ok, "mate 2 registers");
  console.log("mate 2 tries mate 1's ID (the live-test scenario)");
  const bad = await reg("20240011", "Karim Said", "B");
  ok(bad.code === "DEVICE_BOUND_OTHER_ID", "rejected as DEVICE_BOUND_OTHER_ID (was ID_TAKEN, which hid the cheat): " + bad.code);
  const log = gas.sheets.AttFlagLog._g;
  ok(log.length >= 2 && log.some(r => r[3] === "DEVICE_BOUND_OTHER_ID" && r[2] === "20240011"), "AttFlagLog row written");
  console.log("legit re-registration is NOT flagged");
  const n0 = gas.sheets.AttFlagLog._g.length;
  ok((await reg("20240011", "Mona Adel", "Z")).code === "ID_TAKEN", "new phone claiming a taken ID -> ID_TAKEN (change-device flow)");
  ok((await reg("20240011", "Mona Adel", "A")).code === "ID_TAKEN", "same phone, own ID again -> ID_TAKEN");
  ok(gas.sheets.AttFlagLog._g.length === n0, "...neither writes a flag");
  console.log("attend + other cheat");
  ok((await att("20240011", "A")).ok, "mate 1 attends");
  ok((await att("20240022", "B")).ok, "mate 2 attends");
  ok((await att("20240011", "B")).code === "DEVICE_ID_CONFLICT", "mate 2 checks in as mate 1 -> DEVICE_ID_CONFLICT");
  const live = await api.call("att_live", { ...A, session_id: sid });
  ok(live.ok && Array.isArray(live.feed), "att_live returns feed");
  const f = live.feed, kinds = k => f.filter(e => e.k === k);
  ok(kinds("reg").length === 2 && kinds("att").length === 2 && kinds("bad").length === 2, `feed has 2 registered, 2 attended, 2 cheating (${f.map(e => e.k).join(",")})`);
  ok(kinds("reg").every(e => e.n && e.id) && kinds("att").every(e => e.n && e.id), "registered/attended carry name + id");
  const bads = kinds("bad");
  ok(bads.every(e => Object.keys(e).sort().join() === "d,k,l,t"), "cheating events carry ONLY first letter + last 2 digits (+kind, time)");
  ok(bads.every(e => e.l === "K" && e.d === "22"), "...and identify the cheater (device owner Karim, ID ..22), not the victim");
  const raw = JSON.stringify(bads);
  ok(!/Karim|Mona|20240022|20240011/.test(raw), "no full name or ID anywhere in cheating events");
  ok(f.every((e, i) => i === 0 || f[i - 1].t >= e.t), "feed newest first");
  ok(!JSON.stringify(live).includes("secret"), "no secrets in feed");
  ok((await api.call("att_live", { session_id: sid })).code === "UNAUTHORIZED", "feed needs admin token");
  console.log("\n" + pass + " checks passed");
})().catch(e => { console.error("\nFAIL:", e.message); process.exit(1); });
